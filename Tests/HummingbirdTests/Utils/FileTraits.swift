import NIOCore
import SystemPackage
import Testing
import _NIOFileSystem

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif

/// Test trait that will create a temporary folder to be used by a test or test suite
struct TempFolderTrait: TestScoping, SuiteTrait, TestTrait {
    @TaskLocal
    static var folder: String = "."

    let path: String

    init(_ path: String) {
        self.path = path
    }

    func provideScope(for test: Test, testCase: Test.Case?, performing function: @Sendable () async throws -> Void) async throws {
        try await FileSystem.shared.createDirectory(at: .init(path), withIntermediateDirectories: true)
        do {
            try await TempFolderTrait.$folder.withValue(self.path) {
                try await function()
            }
            _ = try await FileSystem.shared.removeItem(at: .init(path), recursively: true)
        } catch {
            _ = try? await FileSystem.shared.removeItem(at: .init(path), recursively: true)
            throw error
        }
    }
}

extension SuiteTrait where Self == TempFolderTrait {
    /// Test trait that will create a temporary folder for the duration of a test or test suite
    ///
    /// When using this trait the task local `TempFolderTrait.folder`` with hold the folder path.
    static func tempFolder(_ folder: String) -> Self { TempFolderTrait(folder) }
}

extension TestTrait where Self == TempFolderTrait {
    /// Test trait that will create a temporary folder for the duration of a test or test suite
    ///
    /// When using this trait the task local `TempFolderTrait.folder`` with hold the folder path.
    static func tempFolder(_ folder: String) -> Self { TempFolderTrait(folder) }
}

/// Test trait that will create a temporary file for the duration of a test or test suite.
///
/// If this trait is combined with ``TempFolderTrait`` the file will be placed in the
/// folder generated by that trait
///
/// When using this trait the task local `TempFileTrait.file` with hold details of the file.
struct TempFileTrait: TestScoping, TestTrait {
    static func randomBuffer(size: Int) -> ByteBuffer {
        var data = [UInt8](repeating: 0, count: size)
        data = data.map { _ in UInt8.random(in: 0...255) }
        return ByteBufferAllocator().buffer(bytes: data)
    }

    enum Filename: ExpressibleByStringLiteral {
        case testname
        case path(String)
        case randomNameWithExtension(String)

        init(stringLiteral value: StringLiteralType) {
            self = .path(.init(value))
        }
    }

    /// Temporary file details
    struct File {
        let path: String
        let contents: ByteBuffer

        var fullPath: String {
            FilePath(TempFolderTrait.folder).appending(self.path).string
        }
    }
    @TaskLocal
    static var file: File = .init(path: ".", contents: ByteBuffer())

    let filename: Filename
    let contents: ByteBuffer

    init(_ filename: Filename, contents: ByteBuffer) {
        self.filename = filename
        self.contents = contents
    }

    func provideScope(for test: Test, testCase: Test.Case?, performing function: @Sendable () async throws -> Void) async throws {
        let path =
            switch self.filename {
            case .path(let path): path
            case .testname: test.name
            case .randomNameWithExtension(let ext): "\(UUID().uuidString).\(ext)"
            }

        let fullPath = FilePath(TempFolderTrait.folder).appending(path)
        let containingFolder = fullPath.removingLastComponent()
        try await FileSystem.shared.createDirectory(at: containingFolder, withIntermediateDirectories: true)
        try await FileSystem.shared.withFileHandle(forWritingAt: fullPath) { write in
            _ = try await write.write(contentsOf: contents, toAbsoluteOffset: 0)
        }
        do {
            try await TempFileTrait.$file.withValue(File(path: path, contents: self.contents)) {
                try await function()
            }
            _ = try await FileSystem.shared.removeItem(at: fullPath)
        } catch {
            _ = try? await FileSystem.shared.removeItem(at: fullPath)
            throw error
        }
    }
}

extension TestTrait where Self == TempFileTrait {
    /// Test trait that will create a temporary file for the duration of a test or test suite.
    ///
    /// If this trait is combined with ``TempFolderTrait`` the file will be placed in the
    /// folder generated by that trait
    ///
    /// When using this trait the task local `TempFileTrait.file` with hold details of the file.
    static func tempFile(_ file: TempFileTrait.Filename = .testname, contents: ByteBuffer = Self.randomBuffer(size: 256)) -> Self {
        TempFileTrait(file, contents: contents)
    }
    /// Test trait that will create a temporary file for the duration of a test or test suite.
    ///
    /// If this trait is combined with ``TempFolderTrait`` the file will be placed in the
    /// folder generated by that trait
    ///
    /// When using this trait the task local `TempFileTrait.file` with hold details of the file.
    static func tempFile(_ file: TempFileTrait.Filename = .testname, contentSize: Int) -> Self {
        TempFileTrait(file, contents: Self.randomBuffer(size: contentSize))
    }
    /// Test trait that will create a temporary file for the duration of a test or test suite.
    ///
    /// If this trait is combined with ``TempFolderTrait`` the file will be placed in the
    /// folder generated by that trait
    ///
    /// When using this trait the task local `TempFileTrait.file` with hold details of the file.
    static func tempFile(_ file: TempFileTrait.Filename = .testname, contents: String) -> Self {
        TempFileTrait(file, contents: ByteBuffer(string: contents))
    }
}
